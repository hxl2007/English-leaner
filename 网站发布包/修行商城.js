export function 商品状态(物,存档,当前境界,余额){
 if(物.境界!==当前境界)return {可买:false,原因:`仅限${物.境界}兑换`};
 if(物.类别!=='丹药'&&Number(存档.背包?.[物.编号])>0)return {可买:false,原因:'已拥有'};
 if(余额<物.价格)return {可买:false,原因:'金币不足'};
 return {可买:true,原因:'兑换'};
}
export function 合并境界小段(本,另,本期,另期){
 const 读=(s,期,名)=>Math.max(1,Math.min(9,Number(s.境界小段?.[名])||(!s.境界小段&&名===期?Number(s.小段):1)||1));
 return Object.fromEntries(境界.map(名=>[名,Math.max(读(本,本期,名),读(另,另期,名))]));
}
