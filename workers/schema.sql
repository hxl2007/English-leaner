-- D1 数据库初始化脚本

-- 用户表
CREATE TABLE IF NOT EXISTS 用户 (
  手机号 TEXT PRIMARY KEY,
  密码 TEXT NOT NULL,
  名称 TEXT NOT NULL DEFAULT '',
  禁用 INTEGER NOT NULL DEFAULT 0,
  注册时间 INTEGER NOT NULL,
  最后登录 INTEGER NOT NULL
);

-- 创建索引
CREATE INDEX IF NOT EXISTS idx_最后登录 ON 用户(最后登录);
CREATE INDEX IF NOT EXISTS idx_禁用 ON 用户(禁用);

CREATE TABLE IF NOT EXISTS 会话 (
  令牌 TEXT PRIMARY KEY,
  手机号 TEXT NOT NULL,
  到期 INTEGER NOT NULL,
  FOREIGN KEY (手机号) REFERENCES 用户(手机号)
);

-- 存档表（可选，用于云端同步学习进度）
CREATE TABLE IF NOT EXISTS 访问限流 (键 TEXT PRIMARY KEY, 截止 INTEGER NOT NULL, 次数 INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS 管理操作 (编号 TEXT PRIMARY KEY, 操作人 TEXT NOT NULL, 目标 TEXT NOT NULL, 动作 TEXT NOT NULL, 时间 INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS 管理操作时间 ON 管理操作(时间);
CREATE TABLE IF NOT EXISTS 题目反馈 (编号 TEXT PRIMARY KEY, 提交人 TEXT NOT NULL, 题号 TEXT NOT NULL, 分类 TEXT NOT NULL, 详情 TEXT NOT NULL, 状态 TEXT NOT NULL DEFAULT '待处理', 回复 TEXT NOT NULL DEFAULT '', 提交时间 INTEGER NOT NULL, 更新时间 INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS 题目反馈时间 ON 题目反馈(提交时间);

-- 已有用户与存档保留。
CREATE TABLE IF NOT EXISTS 存档 (
  手机号 TEXT PRIMARY KEY,
  存档数据 TEXT NOT NULL,
  更新时间 INTEGER NOT NULL,
  FOREIGN KEY (手机号) REFERENCES 用户(手机号)
);
-- 社交功能（v7）：排行榜资料、好友关系、论道（异步 PK）。Worker 首次请求时会自动 CREATE TABLE IF NOT EXISTS。
CREATE TABLE IF NOT EXISTS 社交资料 (手机号 TEXT PRIMARY KEY, 用户键 TEXT NOT NULL DEFAULT '', 公开排行 INTEGER NOT NULL DEFAULT 1, 允许好友 INTEGER NOT NULL DEFAULT 1, 修为 INTEGER NOT NULL DEFAULT 0, 战力 INTEGER NOT NULL DEFAULT 0, 金币 INTEGER NOT NULL DEFAULT 0, 答题数 INTEGER NOT NULL DEFAULT 0, 正确率 INTEGER NOT NULL DEFAULT 0, 练习次数 INTEGER NOT NULL DEFAULT 0, 更新时间 INTEGER NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS 社交资料键 ON 社交资料(用户键);
CREATE TABLE IF NOT EXISTS 好友关系 (编号 TEXT PRIMARY KEY, 发起人 TEXT NOT NULL, 接收人 TEXT NOT NULL, 状态 TEXT NOT NULL DEFAULT '待确认', 创建时间 INTEGER NOT NULL, 更新时间 INTEGER NOT NULL, UNIQUE(发起人,接收人));
CREATE INDEX IF NOT EXISTS 好友关系接收人 ON 好友关系(接收人);
CREATE TABLE IF NOT EXISTS 对战 (编号 TEXT PRIMARY KEY, 发起人 TEXT NOT NULL, 对手 TEXT NOT NULL, 模块 TEXT NOT NULL DEFAULT '单选', 题目编号 TEXT NOT NULL, 状态 TEXT NOT NULL DEFAULT '待应战', 发起人分数 INTEGER, 发起人用时 INTEGER, 对手分数 INTEGER, 对手用时 INTEGER, 创建时间 INTEGER NOT NULL, 更新时间 INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS 对战发起人 ON 对战(发起人,创建时间);
CREATE INDEX IF NOT EXISTS 对战对手 ON 对战(对手,创建时间);

-- 实时切磋竞技场（v9）
CREATE TABLE IF NOT EXISTS 竞技场 (
  编号 TEXT PRIMARY KEY,
  发起人 TEXT NOT NULL,
  对手 TEXT NOT NULL,
  题目编号 TEXT NOT NULL,
  状态 TEXT NOT NULL DEFAULT '待接受',
  发起人血量 INTEGER NOT NULL DEFAULT 100,
  对手血量 INTEGER NOT NULL DEFAULT 100,
  发起人连击 INTEGER NOT NULL DEFAULT 0,
  对手连击 INTEGER NOT NULL DEFAULT 0,
  发起人进度 INTEGER NOT NULL DEFAULT 0,
  对手进度 INTEGER NOT NULL DEFAULT 0,
  发起人武器 TEXT NOT NULL DEFAULT '',
  对手武器 TEXT NOT NULL DEFAULT '',
  发起人答卷 TEXT NOT NULL DEFAULT '{}',
  对手答卷 TEXT NOT NULL DEFAULT '{}',
  回合日志 TEXT NOT NULL DEFAULT '[]',
  胜者 TEXT,
  创建时间 INTEGER NOT NULL,
  更新时间 INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS 竞技场双方 ON 竞技场(发起人,对手,创建时间);
